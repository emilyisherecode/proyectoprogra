    public void actualizarCapitulo(RegisterLecciones lecciones, int cap) {
        lblCapitulo.setText("Capítulo " + (cap+1));
        lblTitulo.setText(envolver(lecciones.getTitulo(cap)));
        lblDescripcion.setText(envolver(lecciones.getDescripcion(cap)));
        lblObjetivo.setText(envolver(lecciones.getObjetivo(cap)));
        lblExplicacion.setText(envolver(lecciones.getExplicacion(cap)));
        lblIndicacion.setText(envolver(lecciones.getIndicacion(cap)));
    }
    
    private void centrarTextos() {
        javax.swing.JLabel[] labels = {lblCapitulo, lblTitulo, lblDescripcion, lblObjetivo, lblExplicacion, lblIndicacion};
        for (javax.swing.JLabel l : labels) {
            l.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
            l.setVerticalAlignment(javax.swing.SwingConstants.TOP);
        }
    }

    private String envolver(String texto) {
        if (texto == null) {
            texto = "";
        }
        return "<html><div style='text-align:center'>" + texto + "</div></html>";
    }

        public void actualizarPagina(RegisterLecciones lecciones, int cap, int pag ) {
        boolean esVocabulario = lecciones.tipo(cap);

        this.lblProgreso.setText((pag+1) + " de 15");
        this.lblReTem.setText(lecciones.getReTem(cap));
        this.lblEnunciado.setText(lecciones.getEnunciado(cap, pag));

        this.rbOpcion1.setVisible(esVocabulario);
        this.rbOpcion2.setVisible(esVocabulario);
        this.rbOpcion3.setVisible(esVocabulario);
        this.rbOpcion4.setVisible(esVocabulario);
        this.tfRespuesta.setVisible(!esVocabulario);

        if (esVocabulario) {
            this.rbOpcion1.setText(lecciones.getOpciones(cap, pag, 0));
            this.rbOpcion2.setText(lecciones.getOpciones(cap, pag, 1));
            this.rbOpcion3.setText(lecciones.getOpciones(cap, pag, 2));
            this.rbOpcion4.setText(lecciones.getOpciones(cap, pag, 3));
        } else {
            this.tfRespuesta.setText("");
        }
        this.lblResultado.setText("");
        this.lblExplicacion.setText("");
        this.lblRespuesta.setText("");
        }
        
        public void validar(RegisterLecciones lecciones, int pag, int cap) {
        String respuesta = "";
        if (lecciones.tipo(cap)) {                       
            if (rbOpcion1.isSelected()) {
                respuesta = rbOpcion1.getText();
            } else if (rbOpcion2.isSelected()) {
                respuesta = rbOpcion2.getText();
            } else if (rbOpcion3.isSelected()) {
                respuesta = rbOpcion3.getText();
            } else if (rbOpcion4.isSelected()) {
                respuesta = rbOpcion4.getText();
            }
        } else {                                         
            respuesta = tfRespuesta.getText().trim();
        }

        if (respuesta.isEmpty()) {
            this.lblResultado.setText("ELIJA O ESCRIBA UNA RESPUESTA");
            return;
        }

        this.lblExplicacion.setText(lecciones.getExplicacionPregunta(cap, pag));
        if (lecciones.getValidar(cap, pag, respuesta)) {
            this.lblResultado.setText("¡CORRECTO!");
        } else {
            this.lblResultado.setText("¡INCORRECTO!");
        }
        this.lblRespuesta.setText(lecciones.getRespuesta(cap, pag));
        }
